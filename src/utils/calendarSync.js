// Utilidad central para sincronizar y unificar automáticamente todos los eventos académicos
// diplomados, cursos, conferencias, programas para organizaciones y fechas clave del calendario.

export const MONTH_MAP_ES = {
  enero: '01', jan: '01', january: '01',
  febrero: '02', feb: '02', february: '02',
  marzo: '03', mar: '03', march: '03',
  abril: '04', abr: '04', apr: '04', april: '04',
  mayo: '05', may: '05',
  junio: '06', jun: '06', june: '06',
  julio: '07', jul: '07', july: '07',
  agosto: '08', ago: '08', aug: '08', august: '08',
  septiembre: '09', sep: '09', sept: '09', september: '09',
  octubre: '10', oct: '10', october: '10',
  noviembre: '11', nov: '11', november: '11',
  diciembre: '12', dic: '12', dec: '12', december: '12',
};

/**
 * Convierte strings de fechas en lenguaje natural o ISO a formato YYYY-MM-DD
 */
export function parseDateToISO(dateStr, defaultYear = 2026) {
  if (!dateStr || typeof dateStr !== 'string') return null;
  const isoMatch = dateStr.match(/\b(20\d{2})-(\d{2})-(\d{2})\b/);
  if (isoMatch) return isoMatch[0];

  const clean = dateStr.toLowerCase();
  const yearMatch = clean.match(/\b(20\d{2})\b/);
  const year = yearMatch ? yearMatch[1] : String(defaultYear);

  let month = null;
  for (const [mName, mNum] of Object.entries(MONTH_MAP_ES)) {
    const reg = new RegExp(`\\b${mName}\\b`, 'i');
    if (reg.test(clean)) {
      month = mNum;
      break;
    }
  }
  if (!month) return null;

  const nums = clean.match(/\b([1-9]|[12]\d|3[01])\b/g);
  const validDays = (nums || []).filter((n) => n !== year);
  const day = validDays.length > 0 ? validDays[0].padStart(2, '0') : '01';

  return `${year}-${month}-${day}`;
}

/**
 * Genera el calendario académico unificado agregando en tiempo real:
 * - Diplomados
 * - Cursos & Talleres
 * - Conferencias & Webinars
 * - Programas para Organizaciones
 * - Eventos manuales del calendario
 */
export function getUnifiedAcademicCalendar(trainingData) {
  if (!trainingData) return [];

  const unified = [];
  const processedKeys = new Set();

  // 1. DIPLOMADOS
  (trainingData.diplomados || []).forEach((dip, idx) => {
    const dateStr = dip.date || dip.dates || '';
    const isoDate = parseDateToISO(dateStr) || `2026-05-${String(12 + idx * 7).padStart(2, '0')}`;
    const evId = `auto-dip-${dip.id || idx}`;
    processedKeys.add(evId);

    unified.push({
      id: evId,
      sourceId: dip.id,
      sourceType: 'diplomado',
      date: isoDate,
      time: dip.time || '18:00 - 21:00 CET',
      category: 'Diplomado',
      modality: dip.duration || 'Modalidad Híbrida',
      badge: dip.badge || 'Certificación Internacional CGA',
      title: dip.title,
      desc: dip.desc,
      link: '/capacitacion#diplomados',
      featured: true,
      autoGenerated: true,
    });
  });

  // 2. CURSOS & TALLERES
  (trainingData.cursos || []).forEach((cur, idx) => {
    const dateStr = cur.date || cur.dates || '';
    const isoDate = parseDateToISO(dateStr) || `2026-06-${String(15 + idx * 5).padStart(2, '0')}`;
    const evId = `auto-cur-${cur.id || idx}`;
    processedKeys.add(evId);

    unified.push({
      id: evId,
      sourceId: cur.id,
      sourceType: 'curso',
      date: isoDate,
      time: cur.time || '16:00 hrs CDMX',
      category: 'Cursos & Talleres',
      modality: cur.hours || cur.modality || 'Taller Intensivo',
      badge: cur.instructor || 'Taller Especializado',
      title: cur.title,
      desc: cur.desc,
      link: '/capacitacion#cursos',
      featured: false,
      autoGenerated: true,
    });
  });

  // 3. CONFERENCIAS & WEBINARS
  (trainingData.webinars || []).forEach((web, idx) => {
    const dateStr = web.date || '';
    const isoDate = parseDateToISO(dateStr) || `2026-05-${String(28 + idx * 10).padStart(2, '0')}`;
    const evId = `auto-web-${web.id || idx}`;
    processedKeys.add(evId);

    unified.push({
      id: evId,
      sourceId: web.id,
      sourceType: 'webinar',
      date: isoDate,
      time: web.time || (dateStr.includes('·') ? dateStr.split('·')[1]?.trim() : '17:00 CET'),
      category: 'Conferencia',
      modality: web.type || web.format || 'Masterclass Abierta',
      badge: web.speaker || 'Conferencia Magistral',
      title: web.title,
      desc: web.summary || web.desc,
      link: '/capacitacion#webinars',
      featured: true,
      autoGenerated: true,
    });
  });

  // 4. PROGRAMAS PARA ORGANIZACIONES
  const orgPrograms = trainingData.organizaciones?.programs || [];
  orgPrograms.forEach((prog, idx) => {
    const dateStr = prog.date || '';
    const isoDate = parseDateToISO(dateStr) || `2026-05-${String(20 + (idx % 8) * 3).padStart(2, '0')}`;
    const evId = `auto-org-${prog.id || idx}`;
    processedKeys.add(evId);

    unified.push({
      id: evId,
      sourceId: prog.id,
      sourceType: 'organizacion',
      date: isoDate,
      time: 'Convocatoria Abierta',
      category: 'In-Company',
      modality: (prog.modalities || []).join(' · ') || 'Programa a la Medida',
      badge: prog.badge || prog.sector || 'Institucional',
      title: prog.title,
      desc: prog.desc,
      link: '/capacitacion#organizaciones',
      featured: false,
      autoGenerated: true,
    });
  });

  // 5. EVENTOS MANUALES / FECHAS PERSONALIZADAS EN CALENDARIO
  if (Array.isArray(trainingData.calendario)) {
    trainingData.calendario.forEach((ev) => {
      if (!processedKeys.has(ev.id)) {
        unified.push(ev);
      }
    });
  }

  // Ordenar cronológicamente
  return unified.sort((a, b) => {
    const dateA = a.date || '9999-99-99';
    const dateB = b.date || '9999-99-99';
    return dateA.localeCompare(dateB);
  });
}
